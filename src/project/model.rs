/// A produced output artifact collected after a route runs.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Artifact {
    /// Path relative to the execution workspace.
    pub path: String,
    /// Lowercase hex sha256 of the artifact bytes.
    pub content_hash: String,
    /// Length of the artifact in bytes.
    pub bytes_len: u64,
}

/// Provenance of a single execution — where and how it ran.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExecutionProvenance {
    /// The workspace directory the route ran in.
    pub workspace: PathBuf,
    /// The full command vector that was spawned.
    pub command: Vec<String>,
    /// The working directory the command ran in.
    pub cwd: PathBuf,
}

/// The result of running one route.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OExecutionResult {
    /// The route id that produced this result.
    pub route_id: String,
    /// Process exit code, if the process ran to completion.
    pub exit_code: Option<i32>,
    /// Captured stdout bytes.
    #[serde(with = "b64_bytes")]
    pub stdout: Vec<u8>,
    /// Captured stderr bytes.
    #[serde(with = "b64_bytes")]
    pub stderr: Vec<u8>,
    /// Decoded structured value (only for `ResultCodec::Json`).
    pub value: Option<serde_json::Value>,
    /// Collected output artifacts.
    pub artifacts: Vec<Artifact>,
    /// Wall-clock duration in nanoseconds.
    pub duration_ns: u128,
    /// Where/how it ran.
    pub provenance: ExecutionProvenance,
}

impl OExecutionResult {
    /// Whether the process exited successfully (exit code 0).
    pub fn succeeded(&self) -> bool {
        self.exit_code == Some(0)
    }

    /// stdout decoded as UTF-8 (lossy).
    pub fn stdout_text(&self) -> String {
        String::from_utf8_lossy(&self.stdout).to_string()
    }

    /// stderr decoded as UTF-8 (lossy).
    pub fn stderr_text(&self) -> String {
        String::from_utf8_lossy(&self.stderr).to_string()
    }

    /// A compact, human-readable one-run summary.
    pub fn summary(&self) -> String {
        let mut out = String::new();
        let status = match self.exit_code {
            Some(0) => "ok".to_string(),
            Some(code) => format!("exit {code}"),
            None => "no exit code".to_string(),
        };
        out.push_str(&format!(
            "route {} → {} ({} ms)\n",
            self.route_id,
            status,
            self.duration_ns / 1_000_000,
        ));
        out.push_str(&format!(
            "  command: {}\n",
            self.provenance.command.join(" ")
        ));
        out.push_str(&format!("  cwd: {}\n", self.provenance.cwd.display()));
        let stdout = self.stdout_text();
        if !stdout.trim().is_empty() {
            out.push_str("  stdout:\n");
            for line in stdout.lines() {
                out.push_str(&format!("    {line}\n"));
            }
        }
        let stderr = self.stderr_text();
        if !stderr.trim().is_empty() {
            out.push_str("  stderr:\n");
            for line in stderr.lines() {
                out.push_str(&format!("    {line}\n"));
            }
        }
        if let Some(value) = &self.value {
            out.push_str(&format!("  value: {value}\n"));
        }
        if !self.artifacts.is_empty() {
            out.push_str("  artifacts:\n");
            for artifact in &self.artifacts {
                out.push_str(&format!(
                    "    {} ({} bytes, sha256:{})\n",
                    artifact.path,
                    artifact.bytes_len,
                    &artifact.content_hash[..artifact.content_hash.len().min(12)],
                ));
            }
        }
        out
    }

    /// Render as a `serde_json::Value` (duration stored as a string so large
    /// nanosecond counts never overflow a JSON number).
    pub fn to_json(&self) -> serde_json::Value {
        serde_json::json!({
            "route_id": self.route_id,
            "exit_code": self.exit_code,
            "succeeded": self.succeeded(),
            "stdout": self.stdout_text(),
            "stderr": self.stderr_text(),
            "value": self.value,
            "artifacts": self.artifacts,
            "duration_ns": self.duration_ns.to_string(),
            "provenance": {
                "workspace": self.provenance.workspace.display().to_string(),
                "command": self.provenance.command,
                "cwd": self.provenance.cwd.display().to_string(),
            },
        })
    }
}
