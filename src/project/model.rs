/// The policy that decides which alternative(s) of a [`RouteSet`] execute.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum RoutePolicy {
    /// Run exactly the named route id.
    Explicit(String),
    /// Run the unambiguous default route.
    #[default]
    Default,
    /// Try alternatives in priority/declared order until one succeeds.
    Fallback,
    /// Run alternatives sequentially, returning the first success.
    AnySuccess,
    /// Race alternatives in parallel, return the first success and cancel
    /// the losers cooperatively.
    RaceSuccess,
    /// Race alternatives in parallel, return the first to settle (success or
    /// failure) and cancel the losers cooperatively.
    RaceSettle,
    /// Run every alternative (each in its own isolated workspace).
    All,
    /// Run all in parallel and verify their results are equivalent
    /// (JSON values when decoded, trimmed stdout otherwise).
    VerifyEquivalent,
    /// Run all in parallel and select the fastest successful alternative.
    BenchmarkAndSelect,
}

impl RoutePolicy {
    /// Parse a policy token as used in the manifest / CLI.
    ///
    /// `explicit` requires the route id to be supplied separately (via
    /// `explicit_id`); when absent it degrades to [`RoutePolicy::Default`]
    /// unless the token itself carries it as `explicit:<id>`.
    pub fn parse(token: &str) -> RoutePolicy {
        let token = token.trim();
        if let Some(rest) = token.strip_prefix("explicit:") {
            return RoutePolicy::Explicit(rest.trim().to_string());
        }
        match token.to_ascii_lowercase().as_str() {
            "explicit" => RoutePolicy::Explicit(String::new()),
            "default" => RoutePolicy::Default,
            "fallback" => RoutePolicy::Fallback,
            "any_success" | "anysuccess" | "any" => RoutePolicy::AnySuccess,
            "race_success" | "racesuccess" | "race" => RoutePolicy::RaceSuccess,
            "race_settle" | "racesettle" => RoutePolicy::RaceSettle,
            "all" => RoutePolicy::All,
            "verify_equivalent" | "verifyequivalent" | "verify" => RoutePolicy::VerifyEquivalent,
            "benchmark_and_select" | "benchmarkandselect" | "benchmark" => {
                RoutePolicy::BenchmarkAndSelect
            }
            _ => RoutePolicy::Default,
        }
    }

    /// A short human-readable token for this policy.
    pub fn token(&self) -> String {
        match self {
            RoutePolicy::Explicit(id) if id.is_empty() => "explicit".to_string(),
            RoutePolicy::Explicit(id) => format!("explicit:{id}"),
            RoutePolicy::Default => "default".to_string(),
            RoutePolicy::Fallback => "fallback".to_string(),
            RoutePolicy::AnySuccess => "any_success".to_string(),
            RoutePolicy::RaceSuccess => "race_success".to_string(),
            RoutePolicy::RaceSettle => "race_settle".to_string(),
            RoutePolicy::All => "all".to_string(),
            RoutePolicy::VerifyEquivalent => "verify_equivalent".to_string(),
            RoutePolicy::BenchmarkAndSelect => "benchmark_and_select".to_string(),
        }
    }

    /// Whether the route runtime can currently execute this policy.
    /// Every represented policy is now executable.
    pub fn is_executable(&self) -> bool {
        true
    }
}

/// A named set of alternative routes providing the same capability.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RouteSet {
    /// The capability token these routes provide.
    pub provides: String,
    /// Candidate route ids, in declared order.
    pub alternatives: Vec<String>,
    /// How to select among the alternatives.
    pub policy: RoutePolicy,
}

