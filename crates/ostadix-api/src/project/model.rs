/// The broad category of a route, used for reporting and lowering.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum RouteKind {
    /// A language interpreter invoked with a script (e.g. `python3 main.py`).
    InterpreterCommand,
    /// A prebuilt native binary invoked directly.
    CompiledBinary,
    /// A build step that produces artifacts (e.g. `cargo build`).
    BuildTarget,
    /// A package-declared entrypoint (`[project.scripts]`, `bin`, …).
    PackageEntrypoint,
    /// A shell task / script runner target (npm scripts, Makefile targets).
    #[default]
    ShellTask,
    /// An O-lang evaluator block.
    OEvaluator,
    /// A composite route that sequences prerequisites into one logical run.
    Composite,
}

/// How the stdout of a route should be interpreted into a structured value.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum ResultCodec {
    /// Treat stdout as opaque UTF-8 text.
    #[default]
    Text,
    /// Parse stdout as JSON into `OExecutionResult.value`.
    Json,
    /// Treat stdout as raw bytes only.
    Bytes,
}

impl ResultCodec {
    /// Parse a manifest/CLI codec token. Unknown tokens fall back to `Text`.
    pub fn parse(token: &str) -> ResultCodec {
        match token.trim().to_ascii_lowercase().as_str() {
            "json" => ResultCodec::Json,
            "bytes" | "binary" | "blob" => ResultCodec::Bytes,
            _ => ResultCodec::Text,
        }
    }
}

/// A precondition that must hold before a route may run.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum RouteGuard {
    /// The host OS (`std::env::consts::OS`) must equal this value.
    PlatformOs(String),
    /// The named command must be resolvable on `PATH`.
    CommandAvailable(String),
    /// The named environment variable must be set (non-empty).
    EnvVarSet(String),
}

/// Where a route came from — used for reporting and manifest-wins merging.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum RouteProvenance {
    /// Declared explicitly in the project manifest at `path`.
    Manifest { path: String },
    /// Auto-discovered by an ecosystem probe, with human-readable evidence.
    Discovered { ecosystem: String, evidence: String },
    /// Injected/overridden from the command line.
    CliOverride,
}

/// Declared read/write effects of a route. Resource keys are opaque strings
/// like `project:out/**`, `host:/tmp/x`, `env:PATH`, or `network`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct RouteEffects {
    /// The route is known to have no observable side effects.
    pub pure: bool,
    /// The route's effects are unknown / unconstrained (the safe default).
    pub unknown: bool,
    /// Resource keys the route reads.
    pub reads: Vec<String>,
    /// Resource keys the route writes.
    pub writes: Vec<String>,
}

impl RouteEffects {
    /// The conservative default: effects unknown.
    pub fn unknown() -> RouteEffects {
        RouteEffects {
            pure: false,
            unknown: true,
            reads: Vec::new(),
            writes: Vec::new(),
        }
    }
}

/// Evidence supplied by a route contract for continuing with another
/// implementation after this route has executed and settled unsuccessfully.
///
/// This is deliberately narrow. `DeclaredIdempotent` is a bundle-bound author
/// declaration, not proof that the hosted command was sandboxed or that its
/// effects were independently verified. The HGraph coordinator records that
/// exact provenance when it relies on the declaration.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RouteFailureContinuation {
    /// No safe post-execution continuation contract is available.
    #[default]
    Unproven,
    /// Repeating the logical operation after this route settles unsuccessfully
    /// is declared idempotent by the bundle author.
    DeclaredIdempotent,
}

impl RouteFailureContinuation {
    /// Parse the manifest/CLI token without weakening an unknown value to the
    /// fail-closed default silently.
    pub fn parse_checked(token: &str) -> Result<Self, String> {
        match token.trim().to_ascii_lowercase().as_str() {
            "unproven" | "deny" => Ok(Self::Unproven),
            "declared_idempotent" => Ok(Self::DeclaredIdempotent),
            other => Err(format!(
                "unknown failure continuation `{other}`; expected unproven or declared_idempotent"
            )),
        }
    }

    pub const fn token(self) -> &'static str {
        match self {
            Self::Unproven => "unproven",
            Self::DeclaredIdempotent => "declared_idempotent",
        }
    }
}

/// A single, concrete, runnable route through the project.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RouteSpec {
    /// Stable identifier, unique within a bundle.
    pub id: String,
    /// Human-readable label.
    pub label: String,
    /// Broad category.
    pub kind: RouteKind,
    /// The command vector: `command[0]` is the program, the rest are the fixed
    /// leading arguments. `arguments` are appended after these.
    pub command: Vec<String>,
    /// The O-lang evaluator name, when this route runs through one.
    pub evaluator: Option<String>,
    /// The primary entrypoint file (relative path), when applicable.
    pub entrypoint: Option<String>,
    /// Working directory, relative to the project root (`.` for the root).
    pub working_directory: String,
    /// Extra arguments appended to `command`.
    pub arguments: Vec<String>,
    /// Environment overlay applied when running.
    pub environment: BTreeMap<String, String>,
    /// Route ids that must run (in a shared workspace) before this one.
    pub prerequisites: Vec<String>,
    /// Declared input resource keys.
    pub inputs: Vec<String>,
    /// Declared output globs (relative), collected as artifacts after a run.
    pub outputs: Vec<String>,
    /// Declared effects.
    pub effects: RouteEffects,
    /// Bundle-author evidence governing whether ordered selection may continue
    /// after this route actually executes and settles unsuccessfully.
    #[serde(default)]
    pub failure_continuation: RouteFailureContinuation,
    /// How to decode stdout.
    pub result_codec: ResultCodec,
    /// Capability tokens this route provides (used by route sets).
    pub provides: Vec<String>,
    /// Guards evaluated before running.
    pub guards: Vec<RouteGuard>,
    /// Selection priority; higher wins in fallback ordering.
    pub priority: i32,
    /// Whether this route is (a candidate for) the project default.
    pub is_default: bool,
    /// Where this route came from.
    pub provenance: RouteProvenance,
}

impl RouteSpec {
    /// Construct a minimal route with sensible defaults.
    pub fn new(id: impl Into<String>, provenance: RouteProvenance) -> RouteSpec {
        let id = id.into();
        RouteSpec {
            label: id.clone(),
            id,
            kind: RouteKind::default(),
            command: Vec::new(),
            evaluator: None,
            entrypoint: None,
            working_directory: ".".to_string(),
            arguments: Vec::new(),
            environment: BTreeMap::new(),
            prerequisites: Vec::new(),
            inputs: Vec::new(),
            outputs: Vec::new(),
            effects: RouteEffects::unknown(),
            failure_continuation: RouteFailureContinuation::Unproven,
            result_codec: ResultCodec::Text,
            provides: Vec::new(),
            guards: Vec::new(),
            priority: 0,
            is_default: false,
            provenance,
        }
    }

    /// The full argument vector (`command` followed by `arguments`).
    pub fn full_command(&self) -> Vec<String> {
        let mut v = self.command.clone();
        v.extend(self.arguments.iter().cloned());
        v
    }
}

