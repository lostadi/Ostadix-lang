//! Core project, route, and result types.
//!
//! Everything here is `serde`-serializable with deterministic ordering
//! (`BTreeMap` for keyed collections, `Vec` for ordered collections). These
//! types are the vocabulary shared by bundling, discovery, manifest parsing,
//! materialization, the route runtime, and the `.O` lowering.

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::BTreeMap;
use std::path::PathBuf;

/// The on-disk/on-wire format version of a [`ProjectBundle`].
pub const BUNDLE_FORMAT_VERSION: u32 = 2;

// ─────────────────────────────────────────────────────────────────────────────
// base64 helper for byte payloads inside JSON
// ─────────────────────────────────────────────────────────────────────────────

/// Serialize `Vec<u8>` as a base64 string so JSON bundles stay text-clean and
/// lossless for arbitrary binary assets.
pub(crate) mod b64_bytes {
    use base64::{engine::general_purpose::STANDARD as B64, Engine};
    use serde::{Deserialize, Deserializer, Serializer};

    pub fn serialize<S: Serializer>(bytes: &[u8], s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&B64.encode(bytes))
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<u8>, D::Error> {
        let s = String::deserialize(d)?;
        B64.decode(s.as_bytes()).map_err(serde::de::Error::custom)
    }
}

