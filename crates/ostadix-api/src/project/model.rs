/// A lossless, route-preserving snapshot of an entire project.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectBundle {
    /// Format version (see [`BUNDLE_FORMAT_VERSION`]).
    pub format_version: u32,
    /// Project name.
    pub name: String,
    /// Deterministic fingerprint of the whole file tree.
    pub root_fingerprint: String,
    /// All captured files, in sorted path order.
    pub files: Vec<ProjectFile>,
    /// All routes, both discovered and manifest-declared.
    pub routes: Vec<RouteSpec>,
    /// Route sets grouping alternative routes by capability.
    pub route_sets: Vec<RouteSet>,
    /// The chosen default route id, if unambiguous.
    pub default_route: Option<String>,
    /// Free-form metadata.
    pub metadata: BTreeMap<String, String>,
}

impl ProjectBundle {
    /// An empty bundle with the given name.
    pub fn empty(name: impl Into<String>) -> ProjectBundle {
        ProjectBundle {
            format_version: BUNDLE_FORMAT_VERSION,
            name: name.into(),
            root_fingerprint: String::new(),
            files: Vec::new(),
            routes: Vec::new(),
            route_sets: Vec::new(),
            default_route: None,
            metadata: BTreeMap::new(),
        }
    }

    /// Look up a route by id.
    pub fn route(&self, id: &str) -> Option<&RouteSpec> {
        self.routes.iter().find(|r| r.id == id)
    }

    /// Look up a route set by its `provides` capability token.
    pub fn route_set(&self, provides: &str) -> Option<&RouteSet> {
        self.route_sets.iter().find(|s| s.provides == provides)
    }

    /// Route ids marked `is_default`.
    pub fn default_candidates(&self) -> Vec<&RouteSpec> {
        self.routes.iter().filter(|r| r.is_default).collect()
    }

    /// Resolve the effective default route id, preferring `default_route`,
    /// then a single `is_default` candidate. Returns `None` when ambiguous or
    /// absent.
    pub fn resolved_default(&self) -> Option<String> {
        if let Some(id) = &self.default_route {
            if self.route(id).is_some() {
                return Some(id.clone());
            }
        }
        let candidates = self.default_candidates();
        if candidates.len() == 1 {
            return Some(candidates[0].id.clone());
        }
        None
    }

    /// Render the route table as human-readable text (no execution).
    pub fn route_table(&self) -> String {
        let mut out = String::new();
        let default = self.resolved_default();
        out.push_str(&format!(
            "Project: {}  ({} route{}, {} route set{})\n",
            self.name,
            self.routes.len(),
            if self.routes.len() == 1 { "" } else { "s" },
            self.route_sets.len(),
            if self.route_sets.len() == 1 { "" } else { "s" },
        ));
        if self.routes.is_empty() {
            out.push_str("  (no routes)\n");
        }
        for route in &self.routes {
            let is_default = default.as_deref() == Some(route.id.as_str());
            let marker = if is_default { "*" } else { " " };
            let provenance = match &route.provenance {
                RouteProvenance::Manifest { path } => format!("manifest:{path}"),
                RouteProvenance::Discovered { ecosystem, .. } => {
                    format!("discovered:{ecosystem}")
                }
                RouteProvenance::CliOverride => "cli".to_string(),
            };
            let command = route.full_command().join(" ");
            out.push_str(&format!(
                "{marker} {id}  [{kind:?}]  provides={provides}  {provenance}\n      $ {command}\n",
                id = route.id,
                kind = route.kind,
                provides = if route.provides.is_empty() {
                    "-".to_string()
                } else {
                    route.provides.join(",")
                },
            ));
        }
        for set in &self.route_sets {
            out.push_str(&format!(
                "  set provides={} policy={} alternatives=[{}]\n",
                set.provides,
                set.policy.token(),
                set.alternatives.join(", "),
            ));
        }
        if default.is_none() && !self.routes.is_empty() {
            out.push_str("  (no unambiguous default route — select one with --route)\n");
        }
        out
    }
}

