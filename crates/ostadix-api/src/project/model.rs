/// The semantic role a stored file plays in the project.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum FileRole {
    /// Human-authored source in some language.
    Source,
    /// Binary or textual asset (data, images, fixtures, …).
    Asset,
    /// A build/config manifest (Cargo.toml, package.json, pyproject.toml, …).
    Manifest,
    /// Route metadata generated by O-lang tooling.
    GeneratedRouteMetadata,
    /// A file identified as a runnable entrypoint.
    Entrypoint,
    /// Anything else (empty files, extensionless files, unclassified).
    #[default]
    Other,
}

/// A single file captured losslessly inside a [`ProjectBundle`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProjectFile {
    /// Normalized, relative, `/`-separated path. Never absolute, never `..`.
    pub path: String,
    /// Raw file bytes. Serialized as base64 in JSON.
    #[serde(with = "b64_bytes")]
    pub bytes: Vec<u8>,
    /// Whether the executable bit is set (any of the unix exec bits).
    pub executable: bool,
    /// The full unix permission mode, when known.
    pub unix_mode: Option<u32>,
    /// If this entry is a symlink, its (relative, in-root) target.
    pub symlink_target: Option<String>,
    /// The O-lang backend/evaluator name inferred for this file, if any.
    pub evaluator: Option<String>,
    /// Lowercase hex sha256 of `bytes` (or of the link target for symlinks).
    pub content_hash: String,
    /// The semantic role of this file.
    pub role: FileRole,
}

impl ProjectFile {
    /// True when this entry represents a symbolic link rather than a regular
    /// file.
    pub fn is_symlink(&self) -> bool {
        self.symlink_target.is_some()
    }
}

